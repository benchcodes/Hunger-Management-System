CREATE TABLE IF NOT EXISTS barangays (
  barangay_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS families (
  family_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barangay_id integer NOT NULL REFERENCES barangays(barangay_id),
  household_id varchar(50),
  family_name varchar(150) NOT NULL,
  address varchar(255) NOT NULL,
  head_of_family varchar(150),
  phone varchar(50),
  monthly_income numeric(12,2),
  food_assistance_status varchar(255) NOT NULL DEFAULT 'None',
  is_npa boolean NOT NULL DEFAULT false,
  priority_score integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  image bytea,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS family_members (
  member_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id integer NOT NULL REFERENCES families(family_id) ON DELETE CASCADE,
  first_name varchar(100),
  last_name varchar(100),
  date_of_birth date,
  gender varchar(20),
  relationship varchar(50) NOT NULL DEFAULT 'Other',
  is_pwd boolean NOT NULL DEFAULT false,
  height_cm numeric(5,2),
  weight_kg numeric(5,2),
  nutritional_status varchar(50) NOT NULL DEFAULT 'Unknown'
);

CREATE TABLE IF NOT EXISTS individuals (
  individual_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  date_of_birth date,
  gender varchar(20),
  barangay_id integer REFERENCES barangays(barangay_id),
  registered_by_barangay_id integer,
  status varchar(50),
  height_cm numeric(5,2),
  weight_kg numeric(5,2),
  image bytea,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS food_supplies (
  food_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  food_name varchar(150) NOT NULL,
  unit varchar(50) NOT NULL,
  total_quantity numeric(12,2) NOT NULL DEFAULT 0,
  barangay_id integer REFERENCES barangays(barangay_id) ON DELETE SET NULL,
  type varchar(20) NOT NULL DEFAULT 'food',
  donation_id integer
);

CREATE TABLE IF NOT EXISTS donors (
  donor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donor_name varchar(150) NOT NULL,
  contact_info varchar(255),
  email varchar(255),
  phone varchar(50)
);

CREATE TABLE IF NOT EXISTS donations (
  donation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donor_id integer REFERENCES donors(donor_id) ON DELETE SET NULL,
  food_id integer REFERENCES food_supplies(food_id) ON DELETE SET NULL,
  food_description varchar(255),
  donation_type varchar(20) NOT NULL DEFAULT 'food',
  quantity numeric(12,2) NOT NULL,
  quantity_unit varchar(50) NOT NULL DEFAULT 'kg',
  date_given date NOT NULL,
  image bytea,
  barangay_id integer REFERENCES barangays(barangay_id) ON DELETE SET NULL,
  status varchar(20) NOT NULL DEFAULT 'pending',
  tracking_number varchar(20) UNIQUE,
  approved_by integer,
  approved_at timestamptz,
  rejection_reason text,
  payment_method varchar(50),
  donor_message text,
  is_archived boolean NOT NULL DEFAULT false,
  archived_at timestamptz,
  archived_by integer
);

CREATE TABLE IF NOT EXISTS distribution (
  distribution_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_type varchar(50) NOT NULL,
  family_id integer REFERENCES families(family_id) ON DELETE SET NULL,
  individual_id integer REFERENCES individuals(individual_id) ON DELETE SET NULL,
  barangay_id integer REFERENCES barangays(barangay_id) ON DELETE SET NULL,
  distribution_type varchar(20) NOT NULL DEFAULT 'Food',
  food_id integer REFERENCES food_supplies(food_id) ON DELETE SET NULL,
  quantity numeric(12,2) NOT NULL,
  date_given date NOT NULL,
  status varchar(50) NOT NULL,
  image bytea
);

CREATE TABLE IF NOT EXISTS distribution_activity_logs (
  activity_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  distribution_id integer REFERENCES distribution(distribution_id) ON DELETE SET NULL,
  action varchar(20) NOT NULL,
  staff_user_id varchar(64),
  staff_name varchar(150) NOT NULL,
  staff_email varchar(255),
  distribution_details text,
  performed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
  user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  email varchar(255) NOT NULL UNIQUE,
  password varchar(255) NOT NULL,
  role varchar(20) NOT NULL,
  barangay_id integer REFERENCES barangays(barangay_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

